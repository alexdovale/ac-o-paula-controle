export const icoFrom = (valor, cls = 'w-4 h-4') => {
    const v = String(valor ?? '').replace(/\ufe0f/g, '').trim();
    if (!v) return '';
    if (ICONS[v]) return ico(v, cls);
    if (EMOJI_ICON[v]) return ico(EMOJI_ICON[v], cls);
    return esc(v);
};

// Devolve o nome canônico do ícone (aceita nome ou emoji antigo).
export const nomeIcone = (valor) => {
    const v = String(valor ?? '').replace(/\ufe0f/g, '').trim();
    return ICONS[v] ? v : (EMOJI_ICON[v] || v);
};

if (typeof window !== 'undefined') { window.ico = ico; window.icoFrom = icoFrom; }
